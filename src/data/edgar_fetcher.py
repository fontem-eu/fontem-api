class EdgarFetcher:
    """
    Fetches and structures fundamental financial data from SEC EDGAR 10-K
    filings using the `edgartools` library.
    """

    def __init__(self, identity: str = "bemar-edgar@research.com"):
        """
        Args:
            identity: An e-mail address required by the SEC EDGAR API to
                      identify the data consumer.  Use your own address.
        """
        set_identity(identity)

    # ------------------------------------------------------------------
    def fetch_fundamentals(  # pylint: disable=too-many-locals
        self, ticker: str, years: int = 10
    ) -> Dict:
        """
        Fetch and parse 10-K fundamental data for *ticker*.

        Returns a dict with the following keys, each containing an annual
        pd.Series indexed by integer fiscal year (descending):

            ticker, revenue, net_income, total_assets, total_liabilities,
            equity, operating_cashflow, current_assets, current_liabilities,
            shares_outstanding, eps,
            _balance_sheet, _income, _cashflow   ← raw DataFrames

        Any concept that cannot be located in the filing returns an empty
        Series so callers never need to handle None.
        """
        logger.info("Fetching EDGAR data for %s (%d years)…", ticker, years)

        company = Company(ticker)
        filings = company.get_filings(form="10-K").head(years)

        if len(filings) == 0:
            raise ValueError(f"No 10-K filings found for '{ticker}'")

        xbrls = XBRLS.from_filings(filings)

        bs_df = xbrls.statements.balance_sheet(max_periods=years).to_dataframe()
        inc_df = xbrls.statements.income_statement(max_periods=years).to_dataframe()
        cf_df = xbrls.statements.cashflow_statement(max_periods=years).to_dataframe()

        revenue            = _to_annual_series(_find_concept(inc_df, _REVENUE))
        net_income         = _to_annual_series(_find_concept(inc_df, _NET_INCOME))
        gross_profit       = _to_annual_series(_find_concept(inc_df, _GROSS_PROFIT))
        operating_income   = _to_annual_series(_find_concept(inc_df, _OPERATING_INCOME))
        total_assets       = _to_annual_series(_find_concept(bs_df,  _TOTAL_ASSETS))
        total_liabilities  = _to_annual_series(_find_concept(bs_df,  _TOTAL_LIABILITIES))
        equity             = _to_annual_series(_find_concept(bs_df,  _EQUITY))
        long_term_debt     = _to_annual_series(_find_concept(bs_df,  _LONG_TERM_DEBT))
        operating_cf       = _to_annual_series(_find_concept(cf_df,  _OPERATING_CF))
        current_assets     = _to_annual_series(_find_concept(bs_df,  _CURRENT_ASSETS))
        current_liab       = _to_annual_series(_find_concept(bs_df,  _CURRENT_LIABILITIES))
        shares             = _to_annual_series(_find_concept(bs_df,  _SHARES_OUTSTANDING))
        eps                = _to_annual_series(_find_concept(inc_df, _EPS))
        inventory          = _to_annual_series(_find_concept(bs_df,  _INVENTORY))
        prepaid_expenses   = _to_annual_series(_find_concept(bs_df,  _PREPAID_EXPENSES))
        # edgartools standardises CapEx as a positive magnitude (spending outflow).
        # FCF = operating_cf − capex  (both positive).
        capex = _to_annual_series(_find_concept(cf_df, _CAPEX))

        # Fallback: derive equity from assets − liabilities when not stated
        if equity.empty and not total_assets.empty and not total_liabilities.empty:
            common = total_assets.index.intersection(total_liabilities.index)
            if len(common):
                equity = total_assets[common] - total_liabilities[common]

        # Free Cash Flow = Operating CF − CapEx (both now positive magnitudes)
        fcf = pd.Series(dtype=float)
        if not operating_cf.empty and not capex.empty:
            common = operating_cf.index.intersection(capex.index)
            if len(common):
                fcf = operating_cf[common] - capex[common]

        return {
            "ticker":              ticker.upper(),
            "revenue":             revenue,
            "gross_profit":        gross_profit,
            "operating_income":    operating_income,
            "net_income":          net_income,
            "total_assets":        total_assets,
            "total_liabilities":   total_liabilities,
            "equity":              equity,
            "long_term_debt":      long_term_debt,
            "operating_cashflow":  operating_cf,
            "capex":               capex,
            "free_cashflow":       fcf,
            "current_assets":      current_assets,
            "current_liabilities": current_liab,
            "inventory":           inventory,
            "prepaid_expenses":    prepaid_expenses,
            "shares_outstanding":  shares,
            "eps":                 eps,
            # Raw DataFrames available for debugging / advanced queries
            "_balance_sheet":      bs_df,
            "_income":             inc_df,
            "_cashflow":           cf_df,
        }

    # ------------------------------------------------------------------
    def get_edgar_ticker_list(self) -> List[Dict]:
        """
        Fetch comprehensive list of companies from SEC's bulk company data.

        Uses the official SEC company_tickers.json endpoint which provides
        a complete listing of all companies that file with EDGAR.

        Returns a list of dictionaries with rich company metadata including:
        - symbol, cik, name, sic, sic_description
        - exchange, sector, industry, location
        - Additional fields for search and filtering

        This is a single API call that returns ~10,000+ companies.
        """
        # SEC requires a descriptive User-Agent header identifying the app and
        # a contact email. Without it, requests return 403 Forbidden.
        url = "https://www.sec.gov/files/company_tickers.json"
        headers = {
            "User-Agent": "edgar-gmr-etl/1.0 bemar-edgar@research.com",
            "Accept-Encoding": "gzip, deflate",
        }

        try:
            logger.info("Fetching EDGAR ticker list from SEC bulk endpoint...")
            response = requests.get(url, headers=headers, timeout=30)
            response.raise_for_status()
            data = response.json()

            # Process the data into a rich format for UI.
            # The SEC JSON format is:
            #   {"0": {"cik_str": 320193, "ticker": "AAPL", "title": "Apple Inc."}, ...}
            # Keys are row indices (0, 1, 2 ...), NOT the CIK.
            # The actual CIK lives in company_info["cik_str"].
            tickers = []
            for _idx, company_info in data.items():
                if not isinstance(company_info, dict):
                    continue

                ticker = company_info.get('ticker')
                if not ticker:
                    continue

                # cik_str is an integer in the SEC payload — convert to zero-padded string
                raw_cik = company_info.get('cik_str', '')
                cik_padded = str(raw_cik).zfill(10)

                ticker_info = {
                    'symbol': ticker.upper(),
                    'cik': cik_padded,
                    'name': company_info.get('title', '').strip(),
                    'sic': '',          # not provided by this SEC endpoint
                    'sic_description': 'Unknown',
                    'exchange': self._infer_exchange(ticker),
                    'sector': 'Unknown',
                    'industry': 'Unknown',
                    'country': 'US',
                    'currency': 'USD',
                    'is_active': True,
                    'last_updated': '',
                }

                # Add search-friendly fields
                ticker_info['search_name'] = (
                    f"{ticker_info['name']} {ticker_info['symbol']}".lower()
                )
                ticker_info['search_keywords'] = self._generate_search_keywords(ticker_info)

                tickers.append(ticker_info)

            logger.info("Successfully fetched %d tickers from EDGAR", len(tickers))
            return tickers

        except Exception as e:
            logger.error("Failed to fetch EDGAR ticker list: %s", e)
            raise  # re-raise so the caller (and cache layer) can handle it properly


    # ------------------------------------------------------------------
    # Helper methods for ticker list enrichment
    # ------------------------------------------------------------------

    def _get_sic_description(self, sic_code: Optional[str]) -> str:
        """Map SIC codes to human-readable descriptions."""
        # Common SIC code mappings (can be expanded)
        sic_mappings = {
            '1311': 'Crude Petroleum and Natural Gas',
            '2834': 'Pharmaceutical Preparations',
            '3571': 'Electronic Computers',
            '3661': 'Telephone and Telegraph Apparatus',
            '3674': 'Semiconductors and Related Devices',
            '3711': 'Motor Vehicles and Passenger Car Bodies',
            '4813': 'Telephone Communications',
            '5812': 'Eating Places',
            '7372': 'Prepackaged Software',
            '7373': 'Computer Integrated Systems Design',
        }

        if not sic_code or not isinstance(sic_code, str):
            return "Unknown"

        # Return mapped description or generic based on first digit
        return sic_mappings.get(sic_code, f"Industry (SIC {sic_code})")

    def _infer_exchange(self, ticker: str) -> str:
        """Infer exchange based on ticker conventions."""
        if not ticker:
            return "Unknown"

        # Common exchange patterns
        if ticker.endswith('.O') or ticker.endswith('.OB'):
            return "NASDAQ"
        if ticker.endswith('.N') or ticker.endswith('.NY'):
            return "NYSE"
        if ticker.endswith('.A'):
            return "AMEX"
        if len(ticker) == 1 or len(ticker) == 2:
            return "NYSE"  # Single/double letter tickers are usually NYSE
        return "NASDAQ"  # Default assumption

    def _infer_sector_from_sic(self, sic_code: Optional[str]) -> str:
        """Infer sector from SIC code."""
        if not sic_code or not isinstance(sic_code, str):
            return "Unknown"

        first_digit = sic_code[0] if sic_code else '0'

        sector_map = {
            '0': 'Agriculture, Forestry, and Fishing',
            '1': 'Mining',
            '2': 'Construction',
            '3': 'Manufacturing',
            '4': 'Transportation and Public Utilities',
            '5': 'Wholesale Trade',
            '6': 'Retail Trade',
            '7': 'Finance, Insurance, and Real Estate',
            '8': 'Services',
            '9': 'Public Administration',
        }

        return sector_map.get(first_digit, "Unknown")

    def _infer_industry_from_sic(self, sic_code: Optional[str]) -> str:
        """Infer more specific industry from SIC code."""
        if not sic_code or not isinstance(sic_code, str):
            return "Unknown"

        # Return the SIC description as industry for now
        return self._get_sic_description(sic_code)

    def _generate_search_keywords(self, ticker_info: Dict) -> str:
        """Generate search keywords for better matching."""
        keywords = []

        # Add name variations
        if ticker_info.get('name'):
            keywords.extend(ticker_info['name'].lower().split())

        # Add ticker and common variations
        if ticker_info.get('symbol'):
            ticker = ticker_info['symbol']
            keywords.append(ticker.lower())
            # Remove common suffixes for better matching
            if ticker.endswith('.O') or ticker.endswith('.N') or ticker.endswith('.A'):
                keywords.append(ticker[:-2].lower())

        # Add sector/industry keywords
        if ticker_info.get('sector'):
            keywords.extend(ticker_info['sector'].lower().split())
        if ticker_info.get('industry'):
            keywords.extend(ticker_info['industry'].lower().split())

        return ' '.join(keywords)
